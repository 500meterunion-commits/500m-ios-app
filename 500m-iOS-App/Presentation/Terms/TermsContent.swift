7. 회사는 회원이 본 약관에 따른 의무를 위반하는 경우 서비스 이용을 제한하거나 이용계약을 해지할 수 있고, 그에 따라 발생하는 책임은 회사의 고의 또는 과실이 없는 한 회원이 부담합니다. 회사는 필요한 경우 회원의 위반행위를 관련 정부기관 또는 사법기관에 통지할 수 있습니다.
